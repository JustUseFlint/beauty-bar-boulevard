import asyncio, sys
from playwright.async_api import async_playwright
BASE = sys.argv[1] if len(sys.argv) > 1 else 'http://localhost:8811/beauty-bar-boulevard/'
async def run():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx = await b.new_context(viewport={'width':393,'height':852}, device_scale_factor=2, is_mobile=True, has_touch=True)
        pg = await ctx.new_page(); errs=[]
        pg.on('console', lambda m: errs.append(m.text) if m.type=='error' else None)
        pg.on('pageerror', lambda x: errs.append(str(x)))
        await pg.goto(BASE+'services/', wait_until='networkidle'); await pg.wait_for_timeout(1500)
        await pg.click('[data-add="color"]'); await pg.click('[data-add="cut"]')
        print('tray', await pg.text_content('[data-tray] [data-tray-n]'), await pg.get_attribute('[data-add="color"]','aria-pressed'))
        await pg.click('[data-tab="nails"]'); await pg.wait_for_timeout(400)
        print('hair hidden', await pg.evaluate('document.querySelector("#hair").hidden'))
        await pg.goto(BASE+'looks/', wait_until='networkidle'); await pg.wait_for_timeout(1500)
        await pg.click('[data-open="1"]'); await pg.wait_for_timeout(900)
        print('lb open', await pg.evaluate('document.querySelector("[data-lb]").open'), await pg.text_content('[data-lb-t]'))
        await pg.click('[data-lb-next]'); await pg.wait_for_timeout(500); print('next', await pg.text_content('[data-lb-t]'))
        await pg.click('[data-lb-save]'); await pg.wait_for_timeout(300)
        await pg.screenshot(path='shots/fn-lightbox-m.png')
        await pg.click('[data-lb-close]')
        await pg.goto(BASE+'plan/?w=ashley', wait_until='networkidle'); await pg.wait_for_timeout(1800)
        await pg.click('label:has(input[name=t][value=morning])'); await pg.wait_for_timeout(300)
        await pg.fill('input[name=name]','Sam')
        print('script:', await pg.text_content('[data-c-script]'))
        print('call:', await pg.get_attribute('[data-c-call]','href'), await pg.text_content('[data-c-call-t]'))
        print('prep:', await pg.text_content('[data-c-prep]'))
        print('jump:', await pg.text_content('[data-jump-t]'))
        await pg.click('label:has(input[name=m][value=walk])'); await pg.wait_for_timeout(300)
        print('walk:', await pg.text_content('[data-c-script]'))
        # pick a Friday-ish (day with wd 5)
        fri = await pg.query_selector('input[name=d][data-wd="5"]')
        if fri:
            await pg.click('label:has(input[name=d][data-wd="5"])'); await pg.wait_for_timeout(300)
            print('evening disabled on Fri:', await pg.evaluate('document.querySelector("[data-evening] input").disabled'), await pg.text_content('[data-time-note]'))
        await pg.evaluate('window.scrollTo(0, 900)'); await pg.wait_for_timeout(1500)
        await pg.screenshot(path='shots/fn-plan-m.png')
        await pg.goto(BASE, wait_until='networkidle'); await pg.wait_for_timeout(2000)
        print('dock n', await pg.text_content('.dock-n'))
        await pg.click('[data-sheet-btn]'); await pg.wait_for_timeout(1400)
        await pg.screenshot(path='shots/fn-sheet-m.png')
        print('sheet', await pg.evaluate('document.documentElement.classList.contains("sheet-open")'))
        await pg.click('[data-sheet-btn]'); await pg.wait_for_timeout(600)
        # transition nav
        await pg.click('.dock-plan'); await pg.wait_for_url('**/plan/'); await pg.wait_for_timeout(2000)
        print('nav ok', pg.url, await pg.evaluate('getComputedStyle(document.querySelector(".iris")).clipPath'))
        print('errs', errs)
        await b.close()
asyncio.run(run())
